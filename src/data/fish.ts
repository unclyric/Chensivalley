// Helper to get a fish by ID
export function getFishById(id: string): FishData | undefined {
  return ALL_FISH.find(f => f.id === id);
}

// Get fish available at a location given current conditions
export function getAvailableFish(
  location: FishingLocation,
  season: Season,
  hour: number,
  weather: Weather,
  timeOfDay: number
): FishData[] {
  return ALL_FISH.filter(fish => {
    if (!fish.locations.includes(location)) return false;
    if (!fish.seasons.includes(season)) return false;
    if (fish.weather.length > 0 && !fish.weather.includes(weather)) return false;
    // Check time of day
    let tod: TimeOfDay;
    if (hour >= 5 && hour < 7) tod = TimeOfDay.Dawn;
    else if (hour >= 7 && hour < 12) tod = TimeOfDay.Morning;
    else if (hour >= 12 && hour < 17) tod = TimeOfDay.Afternoon;
    else if (hour >= 17 && hour < 20) tod = TimeOfDay.Evening;
    else tod = TimeOfDay.Night;
    if (!fish.timeOfDay.includes(tod)) return false;
    return true;
  });
}
